import uuid
from django.conf import settings
from django.db import models
from django.db.models import Q


class AssistantConversation(models.Model):
    """Holds a chat thread between a user and the ERP assistant."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        related_name="assistant_conversations",
    )
    title = models.CharField(max_length=255, blank=True, default="")
    language = models.CharField(max_length=10, default="en")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-updated_at"]
        verbose_name = "Assistant Conversation"
        verbose_name_plural = "Assistant Conversations"

    def __str__(self):
        return f"AssistantConversation {self.pk} ({self.user})"


class AssistantMessage(models.Model):
    """Append-only message log for an assistant turn."""

    ROLE_CHOICES = [
        ("user", "User"),
        ("assistant", "Assistant"),
        ("tool", "Tool"),
    ]
    INPUT_MODE_CHOICES = [
        ("text", "Text"),
        ("voice", "Voice"),
    ]

    conversation = models.ForeignKey(
        AssistantConversation,
        on_delete=models.CASCADE,
        related_name="messages",
    )
    role = models.CharField(max_length=20, choices=ROLE_CHOICES)
    content = models.TextField(blank=True, default="")
    input_mode = models.CharField(max_length=20, choices=INPUT_MODE_CHOICES, default="text")
    steps = models.JSONField(default=list, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]
        verbose_name = "Assistant Message"
        verbose_name_plural = "Assistant Messages"
        constraints = [
            models.CheckConstraint(
                check=Q(role__in=["user", "assistant", "tool"]),
                name="assistant_message_role_valid",
            ),
            models.CheckConstraint(
                check=Q(input_mode__in=["text", "voice"]),
                name="assistant_message_input_mode_valid",
            ),
        ]

    def __str__(self):
        return f"AssistantMessage {self.pk} ({self.role})"


class AssistantProposal(models.Model):
    """Form prefill proposal generated by the assistant."""

    STATUS_CHOICES = [
        ("proposed", "Proposed"),
        ("opened", "Opened"),
        ("saved", "Saved"),
        ("abandoned", "Abandoned"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    message = models.ForeignKey(
        AssistantMessage,
        on_delete=models.CASCADE,
        related_name="proposals",
        null=True,
        blank=True,
    )
    target = models.CharField(max_length=100)  # e.g. "selling.SalesInvoice"
    route = models.CharField(max_length=255, default="")
    values = models.JSONField(default=dict)
    summary = models.TextField(blank=True, default="")
    ai_filled_keys = models.JSONField(default=list, blank=True)
    warnings = models.JSONField(default=list, blank=True)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default="proposed")
    saved_model_label = models.CharField(max_length=100, null=True, blank=True)
    saved_object_id = models.CharField(max_length=100, null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]
        verbose_name = "Assistant Proposal"
        verbose_name_plural = "Assistant Proposals"
        constraints = [
            models.CheckConstraint(
                check=Q(status__in=["proposed", "opened", "saved", "abandoned"]),
                name="assistant_proposal_status_valid",
            ),
            models.CheckConstraint(
                check=(
                    Q(status="saved", saved_model_label__isnull=False, saved_object_id__isnull=False)
                    | (~Q(status="saved") & Q(saved_model_label__isnull=True, saved_object_id__isnull=True))
                ),
                name="assistant_proposal_saved_fields_check",
            ),
        ]

    def __str__(self):
        return f"AssistantProposal {self.pk} ({self.target} - {self.status})"
